// Bundles the Lucide icons the app uses into www/icons.js (works offline).
// Add a name to ICONS below, then run: npm run icons:ui
const fs = require("fs");
const path = require("path");

const ICONS = [
  // navigation & UI
  "house", "phone", "phone-call", "clipboard-list", "building-2", "map", "map-pin", "message-square-warning",
  "search", "chevron-right", "chevron-down", "clock", "navigation", "globe", "mail", "share-2", "copy",
  "message-circle", "crosshair", "trash-2", "plus", "megaphone", "info", "languages", "house-plus", "external-link",
  // hotlines & offices
  "siren", "cross", "life-buoy", "shield", "flame", "hospital", "hand-heart", "landmark", "wallet", "ruler", "scroll-text",
  // services
  "id-card", "file-text", "baby", "store", "hard-hat", "user-round", "accessibility", "users",
  // places
  "waves", "mountain", "mountain-snow", "footprints", "flashlight",
  // report categories
  "construction", "cloud-rain", "lightbulb", "droplets", "tree-pine", "volume-2", "circle-help"
];

const dir = path.join(__dirname, "..", "node_modules", "lucide-static", "icons");
const out = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(path.join(dir, name + ".svg"), "utf8");
  out[name] = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>")).replace(/\s*\n\s*/g, "").trim();
}

const header = "// Generated by scripts/build-icons.js from lucide-static (ISC license, https://lucide.dev). Do not edit.\n";
fs.writeFileSync(path.join(__dirname, "..", "www", "icons.js"), header + "window.ICONS = " + JSON.stringify(out, null, 0) + ";\n");
console.log("www/icons.js: " + ICONS.length + " icons");
